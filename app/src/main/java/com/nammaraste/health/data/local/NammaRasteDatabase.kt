    companion object {

        @Volatile
        private var INSTANCE: NammaRasteDatabase? = null

        val MIGRATION_1_2 = object : Migration(1, 2) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE damage_reports ADD COLUMN isResolved INTEGER NOT NULL DEFAULT 0")
            }
        }
        val MIGRATION_2_3 = object : Migration(2, 3) {
            override fun migrate(database: SupportSQLiteDatabase) {}
        }
        val MIGRATION_3_4 = object : Migration(3, 4) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE roads ADD COLUMN hobli TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN pincode TEXT NOT NULL DEFAULT ''")
            }
        }
        val MIGRATION_4_5 = object : Migration(4, 5) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE roads ADD COLUMN isActive INTEGER NOT NULL DEFAULT 1")
            }
        }
        val MIGRATION_5_6 = object : Migration(5, 6) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("""
                    CREATE TABLE IF NOT EXISTS `routes` (
                        `id` INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
                        `name` TEXT NOT NULL,
                        `startLocation` TEXT NOT NULL,
                        `endLocation` TEXT NOT NULL,
                        `totalDistanceKm` REAL NOT NULL,
                        `description` TEXT NOT NULL,
                        `difficultyLevel` TEXT NOT NULL,
                        `isActive` INTEGER NOT NULL DEFAULT 1
                    )
                """.trimIndent())
            }
        }
        val MIGRATION_6_7 = object : Migration(6, 7) {
            override fun migrate(database: SupportSQLiteDatabase) {
                database.execSQL("ALTER TABLE roads ADD COLUMN potholeCount INTEGER NOT NULL DEFAULT 0")
                database.execSQL("ALTER TABLE roads ADD COLUMN avgTrafficPerDay INTEGER NOT NULL DEFAULT 0")
                database.execSQL("ALTER TABLE roads ADD COLUMN conditionStatus TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN lastInspectionDate TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN maintenancePriority TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN latitude REAL NOT NULL DEFAULT 0.0")
                database.execSQL("ALTER TABLE roads ADD COLUMN longitude REAL NOT NULL DEFAULT 0.0")
                database.execSQL("ALTER TABLE roads ADD COLUMN estimatedRepairCostInr INTEGER NOT NULL DEFAULT 0")
                database.execSQL("ALTER TABLE roads ADD COLUMN reportedByUsers INTEGER NOT NULL DEFAULT 0")
                database.execSQL("ALTER TABLE roads ADD COLUMN streetlightAvailability TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN drainageCondition TEXT NOT NULL DEFAULT ''")
                database.execSQL("ALTER TABLE roads ADD COLUMN accidentRiskScore REAL NOT NULL DEFAULT 0.0")
            }
        }

        fun getDatabase(context: Context): NammaRasteDatabase {
            return INSTANCE ?: synchronized(this) {
                val instance = Room.databaseBuilder(
                    context.applicationContext,
                    NammaRasteDatabase::class.java,
                    "namma_raste_db"
                )
                    .addMigrations(
                        MIGRATION_1_2,
                        MIGRATION_2_3,
                        MIGRATION_3_4,
                        MIGRATION_4_5,
                        MIGRATION_5_6,
                        MIGRATION_6_7
                    )
                    .addCallback(DatabaseCallback(CoroutineScope(Dispatchers.IO)))
                    .build()
                INSTANCE = instance
                instance
            }
        }

